create function private.submit_service_order(p_order_number text,p_service_date date,p_client text,p_technician text,p_model text,p_observations text,p_parts jsonb) returns uuid
language plpgsql security definer set search_path='' as $$
declare v_order_id uuid; v_count integer;
begin
  if p_parts is null or jsonb_typeof(p_parts)<>'array' then raise exception 'Lista inválida'; end if;
  v_count:=jsonb_array_length(p_parts);
  if v_count<1 or v_count>100 then raise exception 'Debe incluir entre 1 y 100 repuestos'; end if;
  if p_service_date is null then raise exception 'La fecha es obligatoria'; end if;
  insert into public.service_orders(order_number,service_date,client,technician,model,observations) values(trim(p_order_number),p_service_date,trim(p_client),trim(p_technician),trim(p_model),left(coalesce(trim(p_observations),''),5000)) returning id into v_order_id;
  insert into public.spare_parts(order_id,code,quantity,description) select v_order_id,trim(x.code),x.quantity,trim(x.description) from jsonb_to_recordset(p_parts) x(code text,quantity integer,description text);
  if (select count(*) from public.spare_parts where order_id=v_order_id)<>v_count then raise exception 'Repuestos incompletos'; end if;
  return v_order_id;
end $$;

create function private.admin_list_service_orders(p_password text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare v_hash text;
begin
  select value into v_hash from private.app_settings where key='admin_password_sha256';
  if v_hash is null or encode(extensions.digest(coalesce(p_password,''),'sha256'),'hex')<>v_hash then raise exception 'Clave incorrecta'; end if;
  return coalesce((select jsonb_agg(jsonb_build_object('id',o.id,'order_number',o.order_number,'service_date',o.service_date,'client',o.client,'technician',o.technician,'model',o.model,'observations',o.observations,'created_at',o.created_at,'parts',coalesce((select jsonb_agg(jsonb_build_object('id',p.id,'code',p.code,'quantity',p.quantity,'description',p.description) order by p.id) from public.spare_parts p where p.order_id=o.id),'[]'::jsonb)) order by o.created_at desc) from public.service_orders o),'[]'::jsonb);
end $$;

