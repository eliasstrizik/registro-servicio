create table public.service_orders (
  id uuid primary key default gen_random_uuid(),
  order_number text not null unique check (char_length(order_number) between 1 and 80),
  service_date date not null default current_date,
  client text not null check (char_length(client) between 1 and 180),
  technician text not null check (char_length(technician) between 1 and 120),
  model text not null check (char_length(model) between 1 and 160),
  observations text not null default '' check (char_length(observations) <= 5000),
  created_at timestamptz not null default now()
);

create table public.spare_parts (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.service_orders(id) on delete cascade,
  code text not null check (char_length(code) between 1 and 100),
  quantity integer not null check (quantity between 1 and 100000),
  description text not null check (char_length(description) between 1 and 500)
);

